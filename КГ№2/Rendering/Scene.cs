namespace КГ_2.Rendering
{
    public static class Scene
    {
        public static List<Polygon3D> Create()
        {
            var list = new List<Polygon3D>();

            // 1. Треугольник (3 ребра), чуть впереди, слева
            list.Add(new Polygon3D(new[]
            {
                new Vec3(-2.6, -1.6, -0.3),
                new Vec3(-0.4, -1.6, -0.1),
                new Vec3(-1.5,  1.0,  0.1),
            }, 230, 80, 80));   // красный

            // 2. Квадрат (4 ребра), наклонён по глубине — пересекается с треугольником
            list.Add(new Polygon3D(new[]
            {
                new Vec3(-0.6, -1.6,  0.2),
                new Vec3( 1.4, -1.6, -0.6),
                new Vec3( 1.4,  0.9, -0.8),
                new Vec3(-0.6,  0.9,  0.4),
            }, 80, 180, 80));   // зелёный

            // 3. Пятиугольник (5 рёбер), сверху, сзади
            list.Add(new Polygon3D(new[]
            {
                new Vec3(-2.8,  1.2,  0.6),
                new Vec3(-1.6,  2.8,  0.9),
                new Vec3( 0.0,  2.2,  0.5),
                new Vec3(-0.4,  0.5,  0.3),
                new Vec3(-2.0,  0.4,  0.8),
            }, 80, 120, 230));  // синий

            // 4. Шестиугольник (6 рёбер), справа, глубоко — перекрывается квадратом
            list.Add(new Polygon3D(new[]
            {
                new Vec3( 1.4, -1.0,  0.5),
                new Vec3( 2.6, -1.0,  0.9),
                new Vec3( 3.0,  0.2,  0.7),
                new Vec3( 2.6,  1.4,  1.1),
                new Vec3( 1.4,  1.4,  0.8),
                new Vec3( 0.9,  0.2,  1.0),
            }, 230, 210, 60));  // жёлтый

            // 5. Маленький треугольник (3 ребра), в центре — пересекается с квадратом и треуг. 1
            list.Add(new Polygon3D(new[]
            {
                new Vec3(-0.2, -1.2, -0.5),
                new Vec3( 0.9, -0.1,  0.1),
                new Vec3(-1.0,  0.0, -0.2),
            }, 200, 80, 200));  // фиолетовый

            // 6. Большой фоновый прямоугольник (4 ребра), самый дальний
            list.Add(new Polygon3D(new[]
            {
                new Vec3(-3.2, -2.2,  1.5),
                new Vec3( 3.2, -2.2,  1.5),
                new Vec3( 3.2,  3.0,  1.5),
                new Vec3(-3.2,  3.0,  1.5),
            }, 120, 120, 120)); // серый — фон

            return list;
        }
    }
}
